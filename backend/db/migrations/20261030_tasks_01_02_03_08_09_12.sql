-- StockRescue P0 security / provenance and active-stock commitment update.
-- Apply once to an existing PostgreSQL database before deploying this code.
-- Idempotent for reruns; create_all() does NOT add Product columns to an existing table.

ALTER TABLE products
    ADD COLUMN IF NOT EXISTS isbn13 VARCHAR(13);

CREATE TABLE IF NOT EXISTS experiment_stock_reservations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id INTEGER NOT NULL REFERENCES rescue_experiments(id) ON DELETE CASCADE,
    product_pk INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    retailer_id VARCHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_active_experiment_product_reservation UNIQUE (product_pk),
    CONSTRAINT uq_experiment_product_reservation UNIQUE (experiment_id, product_pk)
);

CREATE INDEX IF NOT EXISTS ix_experiment_stock_reservations_experiment_id
    ON experiment_stock_reservations (experiment_id);
CREATE INDEX IF NOT EXISTS ix_experiment_stock_reservations_product_pk
    ON experiment_stock_reservations (product_pk);
CREATE INDEX IF NOT EXISTS ix_experiment_stock_reservations_retailer_id
    ON experiment_stock_reservations (retailer_id);
